package Model;
/**
 * Enum che rappresenta i possibili stati del gioco.
 */
public enum GameState {
	    /** Schermata principale. */
	    MENU,
	    /** Partita in corso. */
	    GIOCO,
	    /** Shop tra un livello e l'altro. */
	    SHOP,
	    /** Gioco in pausa. */
	    PAUSA,
	    /** Schermata di game over. */
	    GAME_OVER,
	    /** Schermata di vittoria. */
	    VITTORIA

}
